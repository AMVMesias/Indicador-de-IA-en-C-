/**
 * Main Controller – single entry point called by hooks and commands.
 */

import * as timer from "./timer.ts";
import * as purge from "./purge.ts";
import * as show from "./show.ts";
import * as config from "./config.ts";
import type { PurgeResult } from "./purge.ts";
import type { ShowOutcome } from "./show.ts";

export interface CommandContext {
  command: string;
  args: string;
  model: string;
}

export interface ExtCommandContext {
  projectRoot: string;
  args: string;
}

export interface ExtensionCommand {
  name: string;
  description: string;
  handler: (ctx: ExtCommandContext) => PurgeResult | ShowOutcome;
}

/** Called by the pre-command hook. */
export function preCommand(projectRoot: string, ctx: CommandContext): void {
  timer.recordStart(projectRoot, ctx.command, ctx.args, ctx.model);
}

/** Called by the post-command hook. */
export async function postCommand(
  projectRoot: string,
  specFolder: string,
  ctx: CommandContext,
): Promise<void> {
  // Write the execution timer entry. Human-time estimates are generated by the
  // AI agent directly in the speckit.analytics.end command file (no LLM bridge
  // is available in the Node.js hook process).
  timer.recordEnd(projectRoot, specFolder);
}

/** Purge command handler. */
export function handlePurge(projectRoot: string, args: string): PurgeResult {
  return purge.execute(projectRoot, args);
}

/** Show command handler. */
export function handleShow(projectRoot: string, args: string): ShowOutcome {
  return show.execute(projectRoot, args);
}

/** Register native Spec Kit extension commands. */
export function registerCommands(): ExtensionCommand[] {
  return [
    {
      name: "analytics.purge",
      description:
        "Purge analytics metrics. Use --all to purge everything, or specify a spec name.",
      handler: (ctx: ExtCommandContext) => handlePurge(ctx.projectRoot, ctx.args),
    },
    {
      name: "analytics.show",
      description:
        "Display collected analytics. Pass a spec name, or no argument / --all for the full project.",
      handler: (ctx: ExtCommandContext) => handleShow(ctx.projectRoot, ctx.args),
    },
  ];
}
